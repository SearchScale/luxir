"""Generate NfkcCfData.h from a SHA256-pinned Unicode 15.1.0 UCD directory."""

import argparse
import hashlib
from functools import lru_cache
from pathlib import Path

VERSION = "15.1.0"
HASHES = {
    "DerivedNormalizationProps.txt": "8875dccee2bc1a7c1fe568a3b502a9e78c9e0495afd96b6568b4294d0ed1f7e1",
    "DerivedCombiningClass.txt": "b2e69512b1a96e26105f73e8af42bca6d2e40814683ba31615977f276d6734ff",
    "UnicodeData.txt": "2fc713e6a31a87c4850a37fe2caffa4218180fadb5de86b43a143ddb4581fb86",
}
LIMIT = 0x110000


def fields(text):
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            parts = [p.strip() for p in line.split(";")]
            bounds = parts[0].split("..")
            yield range(int(bounds[0], 16), int(bounds[-1], 16) + 1), parts[1:]


def generate(ucd):
    sources = {}
    for name, expected in HASHES.items():
        path = ucd / name
        if not path.exists():
            path = ucd / "extracted" / name
        data = path.read_bytes()
        actual = hashlib.sha256(data).hexdigest()
        if actual != expected:
            raise ValueError(f"{path}: expected SHA256 {expected}, got {actual}")
        sources[name] = data.decode("utf-8")

    mappings = {}
    qc = bytearray(LIMIT)
    for cps, parts in fields(sources["DerivedNormalizationProps.txt"]):
        if parts[0] == "NFKC_CF":
            value = "".join(chr(int(cp, 16)) for cp in parts[1].split()).encode("utf-8")
            for cp in cps:
                mappings[cp] = value
        elif parts[0] == "NFC_QC" and parts[1] in ("N", "M"):
            for cp in cps:
                qc[cp] = 1
    ccc = bytearray(LIMIT)
    for cps, parts in fields(sources["DerivedCombiningClass.txt"]):
        for cp in cps:
            ccc[cp] = int(parts[0])

    decompositions = {}
    for line in sources["UnicodeData.txt"].splitlines():
        parts = line.split(";")
        decomp = parts[5].split()
        if decomp and decomp[0].startswith("<"):
            decomp = decomp[1:]
        if decomp:
            decompositions[int(parts[0], 16)] = tuple(int(c, 16) for c in decomp)

    @lru_cache(None)
    def nfkd(cp):
        return tuple(c for child in decompositions[cp] for c in nfkd(child)) if cp in decompositions else (cp,)

    # Stream-safe counts use NFKD, including compatibility decompositions, just
    # like uni-algo. Hangul decomposes only to starters, so needs no special case.
    def nonstarters(cp):
        seq = nfkd(cp)
        lead = 0
        for c in seq:
            if not ccc[c]:
                break
            lead += 1
        trail = 0
        for c in reversed(seq):
            if not ccc[c]:
                break
            trail += 1
        assert lead <= 2 and trail <= 3
        # The runtime recurrence adds lead or resets to trail. A decomposition
        # starting with non-starters must therefore contain no later starter.
        assert not lead or lead == len(seq)
        return lead, trail

    pool = bytearray()
    byte_offsets = {}
    records = []
    record_ids = {}
    ids = []
    for cp in range(LIMIT):
        mapping = 0  # zero means identity; nonzero includes empty mappings
        if cp in mappings:
            value = mappings[cp]
            if value not in byte_offsets:
                byte_offsets[value] = len(pool)
                pool.extend(value)
            assert len(value) < 128 and len(pool) < 0x1000000
            mapping = (1 << 31) | (len(value) << 24) | byte_offsets[value]
        lead, trail = nonstarters(cp)
        props = ccc[cp] | (qc[cp] << 8) | (lead << 9) | (trail << 11)
        record = (mapping, props)
        if record not in record_ids:
            record_ids[record] = len(records)
            records.append(record)
        ids.append(record_ids[record])
    assert len(records) < 65536

    def stages(shift):
        blocks = {}
        first, second = [], []
        size = 1 << shift
        for start in range(0, LIMIT, size):
            block = tuple(ids[start:start + size])
            if block not in blocks:
                blocks[block] = len(blocks)
                second.extend(block)
            first.append(blocks[block])
        assert len(blocks) < 65536
        return first, second

    shift = min(range(4, 9), key=lambda s: sum(len(a) for a in stages(s)))
    first, second = stages(shift)
    out = ["// Copyright 2020-2026 Yonik Seeley and Luxir contributors",
           "// SPDX-License-Identifier: Apache-2.0", "// Generated by generate_nfkc_cf_data.py; do not edit.",
           f"// Unicode {VERSION}; SHA256 source hashes:"]
    out += [f"// {name}: {digest}" for name, digest in HASHES.items()]
    out += ["#pragma once", "", "#include <cstdint>", "", "namespace luxir::nfkc_cf_data {",
            "// stage1 selects a deduplicated block of record IDs in stage2.",
            "// Mapping: bit 31 = mapped (including empty), bits 24..30 = byte length,",
            "// bits 0..23 = UTF-8 pool offset. Properties: ccc, NFC_QC != Yes,",
            "// NFKD leading (bits 9..10) and trailing (bits 11..12) non-starters.",
            "struct Record { uint32_t mapping; uint16_t props; };",
            "inline constexpr unsigned unicodeVersion = 15001000;",
            f"inline constexpr unsigned blockShift = {shift};"]

    def array(typ, name, values, width=16):
        out.append(f"inline constexpr {typ} {name}[] = {{")
        for i in range(0, len(values), width):
            out.append("  " + ", ".join(str(v) for v in values[i:i + width]) + ",")
        out.append("};")
    array("uint16_t", "stage1", first)
    array("uint16_t", "stage2", second)
    array("Record", "records", [f"{{0x{m:08x}, {p}}}" for m, p in records], 4)
    array("unsigned char", "utf8", list(pool))
    out += ["inline constexpr const Record& lookup(uint32_t cp) {",
            "  return records[stage2[((unsigned) stage1[cp >> blockShift] << blockShift)",
            "                        + (cp & ((1u << blockShift) - 1))]];", "}",
            "}  // namespace luxir::nfkc_cf_data", ""]
    print(f"{len(first)} stage1 + {len(second)} stage2 entries, {len(records)} records, "
          f"{len(pool)} UTF-8 bytes; {2*(len(first)+len(second))+8*len(records)+len(pool)} bytes")
    return "\n".join(out)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("ucd", type=Path)
    parser.add_argument("--output", type=Path, default=Path(__file__).with_name("NfkcCfData.h"))
    args = parser.parse_args()
    args.output.write_text(generate(args.ucd), encoding="ascii")
